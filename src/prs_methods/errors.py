"""Как метод сообщает платформе, что результата нет.

Платформа смотрит на то, что вернула функция:

* обычное значение (число, строка, список, словарь без ключа ``error``)
  записывается в тег, а у метода чтения отдаётся клиенту;
* словарь ``{"error": "..."}`` в тег не записывается. Платформа пишет
  текст в журнал сервиса методов, у тега остаётся прежнее значение.

Собирать этот словарь вручную не нужно: вызовите ``fail("причина")``.
Любое другое необработанное исключение тоже превратится в ``{"error": ...}``,
и процесс исполнителя продолжит работу.
"""
from typing import NoReturn


class MethodError(Exception):
    """Метод отказался возвращать значение. Текст исключения попадёт в журнал платформы."""


def fail(message: str) -> NoReturn:
    """Прервать метод и оставить значение тега без изменений.

    Пример::

        if divisor == 0:
            fail("деление на ноль")

    Код после ``fail`` не выполняется. Платформа получит ``{"error": message}``.
    Если вызвать функцию метода напрямую, например в тесте, вы увидите
    исключение ``MethodError``.
    """
    raise MethodError(str(message))
