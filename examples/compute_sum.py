"""Тип 0, вычислительный, фиксированные параметры: сумма двух тегов.

Сценарий: в комнате два счётчика энергии — освещение и телевизор.
Тег комнаты «Суммарная энергия» пересчитывается при каждом новом
значении любого из счётчиков.

Настройка на платформе:

1. ``python examples/compute_sum.py --yaml > sum.yaml`` и загрузить файл
   в каталог: конфигуратор, меню папки «Методы», «Загрузка описания».
2. В меню тега «Суммарная энергия»: «Новый метод» → «Ссылка на метод
   из каталога» → «Сумма». Тип — «Вычислительный» (0), инициаторы — оба
   тега счётчиков, параметр ``a`` — тег освещения, ``b`` — тег телевизора.
3. ``amqp_url=amqp://пользователь:пароль@сервер/ python examples/compute_sum.py``.

Результат записывается в тег «Суммарная энергия» с меткой времени
нового значения счётчика.
"""
from prs_methods import main, method, number, param, require_good


@method(
    "acme.energy.sum",
    cn="Сумма",
    description="Складывает последние значения двух аргументов.",
    folder="Энергия",
    parameters=(param("a", "float"), param("b", "float")),
    probe=(2, 3),
)
def sum_energy(a, b):
    # Если у счётчика нет данных или связь потеряна, тег суммы не меняется.
    require_good(a, b)
    return number(a) + number(b)


if __name__ == "__main__":
    main()
