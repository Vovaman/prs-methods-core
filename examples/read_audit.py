"""Тип 3, действие при чтении, фиксированные параметры: журнал чтений тега.

Сценарий: нужно знать, кто и за какой период читает тег «Коммерческий учёт».
Значения по-прежнему отдаёт хранилище, метод только записывает факт чтения.

Настройка на платформе:

1. ``python examples/read_audit.py --yaml > audit.yaml`` и загрузить файл в каталог.
2. В меню тега: «Новый метод» → «Ссылка на метод из каталога» →
   «Журнал чтений». Тип — «Действие при чтении» (3). Параметр ``request`` —
   «Данные из запроса клиента». Тег остаётся привязанным к хранилищу.
3. ``amqp_url=amqp://пользователь:пароль@сервер/ python examples/read_audit.py``.

Ответ клиенту формирует хранилище, а не метод: результат функции
не используется. ``fail`` и исключения попадают только в журнал платформы
и на чтение не влияют.
"""
import logging

from prs_methods import main, method, param

log = logging.getLogger("acme.audit")


@method(
    "acme.audit.read",
    cn="Журнал чтений",
    description="Записывает в журнал, какой тег и за какой период прочитали.",
    folder="Аудит",
    parameters=(param("request", "json", "Запрос клиента"),),
    probe=({"tagId": ["1"], "start": None, "finish": 1_700_000_000_000_000},),
)
def audit_read(request):
    log.warning(
        "чтение тегов %s за период %s..%s",
        request.get("tagId"),
        request.get("start"),
        request.get("finish"),
    )
    return True


if __name__ == "__main__":
    main()
