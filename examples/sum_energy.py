"""Пример вычислительного метода: сумма двух значений.

Сценарий: в комнате два счётчика энергии — освещение и телевизор.
Тег комнаты «Суммарная энергия» должен пересчитываться при каждом
новом значении любого из счётчиков.

Как это настроить:

1. Получить описание для каталога и загрузить его на платформу
   (конфигуратор, папка «Методы», команда «Загрузка описания»)::

       python examples/sum_energy.py --yaml

2. В меню тега «Суммарная энергия» выбрать «Новый метод» → «Ссылка на метод
   из каталога» → «Сумма». Тип — вычислительный (0), инициаторы — оба тега счётчиков,
   параметр ``a`` — тег освещения, параметр ``b`` — тег телевизора.

3. Запустить исполнитель::

       amqp_url=amqp://пользователь:пароль@сервер/ python examples/sum_energy.py

После этого каждое новое значение любого счётчика запишет сумму в тег комнаты.
"""
import sys

from prs_methods import description_yaml, method, number, param, require_good, run


@method(
    "acme.energy.sum",
    cn="Сумма",
    description="Складывает последние значения двух аргументов.",
    folder="Энергия",
    parameters=(param("a", "float"), param("b", "float")),
    probe=(2, 3),
)
def sum_energy(a, b):
    # Если у счётчика нет данных или связь потеряна, тег суммы не меняется.
    require_good(a, b)
    return number(a) + number(b)


if __name__ == "__main__":
    if "--yaml" in sys.argv:
        print(description_yaml(), end="")
    else:
        run()
