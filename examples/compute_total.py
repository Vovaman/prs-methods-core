"""Тип 0, вычислительный, произвольные параметры: сумма любого числа тегов.

Сценарий: тег этажа «Суммарная энергия» складывает счётчики всех комнат.
Комнат на разных этажах разное число, поэтому метод не фиксирует
список параметров: каждая ссылка задаёт столько параметров, сколько нужно.

Настройка на платформе:

1. ``python examples/compute_total.py --yaml > total.yaml`` и загрузить файл в каталог.
2. Загрузчик описания платформы пока не переносит флаг ``variadic``.
   Откройте определение «Сумма всех» в каталоге и включите
   «Произвольные параметры» (или ``PUT /v1/methods/`` с ``prsVariadic: true``).
3. В меню тега этажа: «Новый метод» → «Ссылка на метод из каталога» →
   «Сумма всех». Тип — «Вычислительный» (0), инициаторы — теги комнат,
   параметры — те же теги комнат, сколько угодно.
4. ``amqp_url=amqp://пользователь:пароль@сервер/ python examples/compute_total.py``.
"""
from prs_methods import fail, main, method, number, require_good


@method(
    "acme.energy.total",
    cn="Сумма всех",
    description="Складывает последние значения всех параметров.",
    folder="Энергия",
    variadic=True,
    probe=(1, 2, 3),
)
def total(*args):
    if not args:
        fail("у ссылки на метод нет ни одного параметра")
    require_good(*args)
    return sum(number(arg) for arg in args)


if __name__ == "__main__":
    main()
