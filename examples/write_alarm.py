"""Тип 4, действие при записи, фиксированные параметры: оповещение о превышении.

Сценарий: в тег «Давление» пишет коннектор. Значения сохраняет хранилище,
а метод при каждой записи проверяет их и шлёт оповещение, если давление
выше порога.

Настройка на платформе:

1. ``python examples/write_alarm.py --yaml > alarm.yaml`` и загрузить файл в каталог.
2. В меню тега «Давление»: «Новый метод» → «Ссылка на метод из каталога» →
   «Оповещение о превышении». Тип — «Действие при записи» (4).
   Параметр ``limit`` — литерал, например ``6``. Тег остаётся привязанным к хранилищу.
3. ``amqp_url=amqp://пользователь:пароль@сервер/ python examples/write_alarm.py``.

Записываемые точки приходят последним аргументом, как у метода записи.
Но в отличие от метода записи действие не может отклонить запись:
``fail`` и исключения попадают только в журнал платформы.
"""
from prs_methods import is_good, main, method, moment, number, param, points


def notify(text):
    """Заглушка: здесь должна быть отправка в почту, мессенджер и т. п."""
    print(text)


@method(
    "acme.alarm.pressure",
    cn="Оповещение о превышении",
    description="Оповещает, если записанное значение выше порога.",
    folder="Оповещения",
    parameters=(param("limit", "float", "Порог"),),
    probe=(6, [[1_700_000_000_000_000, 6.4, None]]),
)
def pressure_alarm(limit, written):
    top = number(limit)
    for item in points(written):
        if is_good(item.q) and number(item.y) > top:
            notify(f"{moment(item.x).isoformat()}: давление {item.y} выше {top}")
    return True


if __name__ == "__main__":
    main()
